const fs = require('fs');
const path = require('path');

const PLUGIN_DIR = path.join(__dirname, '..', 'integrations', 'trmnl-running-board');
const DEFAULT_SRC_DIR = path.join(PLUGIN_DIR, 'src');
const OUTPUT_FILE = path.join(PLUGIN_DIR, 'transform.js');
const MODULE_ORDER = ['strings', 'time', 'settings', 'tredict', 'week', 'form', 'runWindow', 'board'];
const HEADER = '// Generated by scripts/build-trmnl.js from src/. Do not edit.';
const RUN = `async function run(input) {
  return buildBoard(input, { fetch, now: Date.now() });
}`;

function stripModuleGlue(source) {
  return source
    .replace(/^const \{[^}]*\} = require\([^)]*\);\n/gm, '')
    .replace(/^module\.exports = \{[^}]*\};\s*$/m, '')
    .trim();
}

function build({ srcDir = DEFAULT_SRC_DIR } = {}) {
  const parts = MODULE_ORDER.map(name => path.join(srcDir, `${name}.js`))
    .filter(file => fs.existsSync(file))
    .map(file => stripModuleGlue(fs.readFileSync(file, 'utf8')));
  return `${[HEADER, ...parts, RUN].join('\n\n')}\n`;
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT_FILE, build());
}

module.exports = { build, OUTPUT_FILE };
