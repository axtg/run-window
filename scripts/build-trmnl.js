const fs = require('fs');
const path = require('path');

const PLUGIN_DIR = path.join(__dirname, '..', 'integrations', 'trmnl-running-board');
const DEFAULT_SRC_DIR = path.join(PLUGIN_DIR, 'src');
const OUTPUT_FILE = path.join(PLUGIN_DIR, 'transform.js');
const MODULE_ORDER = ['strings', 'time', 'settings', 'tredict', 'intensity', 'week', 'form', 'runWindow', 'board'];
const HEADER = '// Generated by scripts/build-trmnl.js from src/. Do not edit.';
// Fixed strings only: buildBoard catches its own errors, this covers anything that escapes it
const RUN = `async function run(input) {
  try {
    return await buildBoard(input, { fetch, now: Date.now() });
  } catch {
    return {
      v: 1,
      lang: 'en',
      fetchedAt: new Date(Date.now()).toISOString(),
      fetchedAtText: '',
      tredict: { state: 'unavailable', message: 'Tredict unavailable' },
      tredictAt: null,
      tredictAtText: '',
      week: null,
      form: null,
      intensity: null,
      run: { kind: 'error', heading: 'Weather unavailable', lines: [] },
      weatherRetryAt: null,
      tredictRetryAt: null,
      intensityCache: [],
      attribution: ''
    };
  }
}`;

function stripModuleGlue(source) {
  return source
    .replace(/^const \{[^}]*\} = require\([^)]*\);\n/gm, '')
    .replace(/^module\.exports = \{[^}]*\};\s*$/m, '')
    .trim();
}

function build({ srcDir = DEFAULT_SRC_DIR } = {}) {
  // A module left out of the order would be dropped from transform.js without a word
  const unknown = fs
    .readdirSync(srcDir)
    .filter(name => name.endsWith('.js') && !MODULE_ORDER.includes(name.slice(0, -3)));
  if (unknown.length > 0) throw new Error(`Not in MODULE_ORDER: ${unknown.join(', ')}`);
  const parts = MODULE_ORDER.map(name => path.join(srcDir, `${name}.js`))
    .filter(file => fs.existsSync(file))
    .map(file => stripModuleGlue(fs.readFileSync(file, 'utf8')));
  return `${[HEADER, ...parts, RUN].join('\n\n')}\n`;
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT_FILE, build());
}

module.exports = { build, OUTPUT_FILE };
