const fs = require('fs');
const os = require('os');
const path = require('path');
const { build } = require('../../scripts/build-trmnl');
const { loadTransform, renderFull } = require('./harness');

const PLUGIN_DIR = path.join(__dirname, '..', '..', 'integrations', 'trmnl-running-board');
const SRC_DIR = path.join(PLUGIN_DIR, 'src');
const MAX_BYTES = 100 * 1024;
const RUN_TEXT = `async function run(input) {
  try {
    return await buildBoard(input, { fetch, now: Date.now() });
  } catch {
    return {
      v: 1,
      lang: 'en',
      fetchedAt: new Date(Date.now()).toISOString(),
      fetchedAtText: '',
      tredict: { state: 'unavailable', message: 'Tredict unavailable' },
      tredictAt: null,
      tredictAtText: '',
      week: null,
      form: null,
      run: { kind: 'error', heading: 'Weather unavailable', lines: [] },
      weatherRetryAt: null,
      attribution: ''
    };
  }
}`;

const sourceFiles = () => fs.readdirSync(SRC_DIR).filter(name => name.endsWith('.js'));
const read = file => fs.readFileSync(path.join(PLUGIN_DIR, file), 'utf8');

describe('build', () => {
  const output = build({ srcDir: SRC_DIR });

  it('starts with the generated-file header and ends with run', () => {
    expect(output.startsWith('// Generated by scripts/build-trmnl.js from src/. Do not edit.')).toBe(true);
    expect(output.trimEnd().endsWith(RUN_TEXT)).toBe(true);
  });

  it('contains no require or module.exports', () => {
    expect(output).not.toMatch(/require\(/);
    expect(output).not.toMatch(/module\.exports/);
  });

  it('contains no console or error message access', () => {
    expect(output).not.toMatch(/console\./);
    expect(output).not.toMatch(/\.message/);
  });

  it('keeps top-level names unique across src and ends each file with one module.exports', () => {
    const seen = new Map();
    for (const file of sourceFiles()) {
      const text = fs.readFileSync(path.join(SRC_DIR, file), 'utf8');
      const names = [];
      for (const match of text.matchAll(/^(?:async\s+)?function\s+(\w+)|^(?:const|let|var)\s+(\w+)\s*=/gm)) {
        names.push(match[1] || match[2]);
      }
      for (const name of names) {
        expect(seen.has(name) ? `${name} in ${seen.get(name)} and ${file}` : null).toBeNull();
        seen.set(name, file);
      }
      expect(text.match(/^module\.exports = \{[^}]*\};\s*$/gm)).toHaveLength(1);
      expect(text.trimEnd()).toMatch(/module\.exports = \{[^}]*\};$/);
      const requires = text.match(/require\(/g) || [];
      const imports = text.match(/^const \{[^}]*\} = require\('\.\/\w+'\);$/gm) || [];
      expect(requires).toHaveLength(imports.length);
    }
  });

  it('matches the committed transform.js', () => {
    expect(read('transform.js')).toBe(output);
  });

  it('keeps plugin files within the size limit', () => {
    for (const file of ['settings.yml', 'full.liquid', 'transform.js']) {
      const filePath = path.join(PLUGIN_DIR, file);
      if (fs.existsSync(filePath)) {
        expect(fs.statSync(filePath).size).toBeLessThanOrEqual(MAX_BYTES);
      }
    }
  });
});

describe('harness', () => {
  it('runs the built script and survives a failing fetch', async () => {
    const now = Date.parse('2026-11-04T10:00:00Z');
    const run = loadTransform({
      fetch: async () => {
        throw new Error('x');
      },
      now
    });
    const result = JSON.parse(JSON.stringify(await run({})));
    expect(result.v).toBe(1);
    expect(result.fetchedAt).toBe('2026-11-04T10:00:00.000Z');
  });

  it('returns the fixed error output when buildBoard throws', async () => {
    const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'trmnl-build-'));
    try {
      fs.writeFileSync(
        path.join(scratch, 'board.js'),
        "function buildBoard() {\n  throw new Error('boom');\n}\n\nmodule.exports = { buildBoard };\n"
      );
      const code = build({ srcDir: scratch });
      const now = Date.parse('2026-11-04T10:00:00Z');
      const run = loadTransform({ fetch: async () => ({}), now, code });
      const result = JSON.parse(JSON.stringify(await run({})));
      expect(result).toEqual({
        v: 1,
        lang: 'en',
        fetchedAt: '2026-11-04T10:00:00.000Z',
        fetchedAtText: '',
        tredict: { state: 'unavailable', message: 'Tredict unavailable' },
        tredictAt: null,
        tredictAtText: '',
        week: null,
        form: null,
        run: { kind: 'error', heading: 'Weather unavailable', lines: [] },
        weatherRetryAt: null,
        attribution: ''
      });
      expect(JSON.stringify(result)).not.toContain('boom');
    } finally {
      fs.rmSync(scratch, { recursive: true, force: true });
    }
  });

  it('escapes printed values in full.liquid', async () => {
    const html = await renderFull({ fetchedAtText: '<b>' });
    expect(html).toContain('&lt;b&gt;');
    expect(html).not.toContain('<b>');
  });
});
